import assert from 'node:assert/strict';
import { initialDb, handleApiRequest } from '../core.mjs';
const db = await initialDb('equipment-turnover-api-password');
const admin = db.users.find(u => u.role === 'admin');
db.sessions.push({id:'turnover-session',token:'turnover-admin',userId:admin.id,expiresAt:'2099-12-31T00:00:00Z'});
const eq = db.equipment.find(e => e.active && e.reservable && e.status === '가능');
const now = '2026-10-12T08:30:00.000Z';
let saves = 0, failSave = false;
const api = (method,pathname,body={}) => handleApiRequest({method,pathname,authorization:'Bearer turnover-admin',readText:async()=>JSON.stringify(body),db,now,saveDb:async()=>{if(failSave)throw new Error('save failed');saves++},slackWebhook:''});
const fields = {reservedDate:'2026-10-12',period:'당일',rentalTime:'17:30',returnTime:'18:00',phone:'01012345678',equipmentItemIds:[eq.id],cameraBagConfirmed:true};
const a = {id:'turnover-a',userId:admin.id,type:'equipment',status:'checked_out',fields:{...fields,reservedDate:'2026-10-09',period:'주말사용',rentalTime:'09:00',returnTime:'17:10'},actualCheckedOutAt:'2026-10-09T00:00:00Z',history:[]};
const b = {id:'turnover-b',userId:admin.id,type:'equipment',status:'approved',fields,history:[]};
db.reservations.push(a,b);
assert.equal((await api('PATCH','/api/admin/reservations/turnover-b/status',{status:'checked_out'})).status,409);
assert.equal((await api('POST','/api/reservations/turnover-a/cancel')).status,409);
assert.equal((await api('DELETE','/api/admin/reservations/turnover-a')).status,409);
assert.equal((await api('PATCH','/api/admin/reservations/turnover-a/status',{status:'returned'})).status,409);
db.settings.equipmentOverdueWarningsEnabled = true;
db.settings.equipmentOverdueWarningsEnabledAt = '2026-10-01T00:00:00Z';
const returned = {actualReturnedAt:'2026-10-12T08:20:00Z',returnTimeNote:'행정 기록 지연',inspections:[{equipmentId:eq.id,outcome:'normal',note:''}]};
assert.equal((await api('POST','/api/admin/reservations/turnover-a/return-inspection',returned)).status,200);
const beforeRetry = saves;
assert.equal((await api('POST','/api/admin/reservations/turnover-a/return-inspection',returned)).status,200);
assert.equal(saves,beforeRetry);
assert.equal((await api('POST','/api/admin/reservations/turnover-a/return-inspection',{...returned,returnTimeNote:'different'})).status,409);
assert.equal((await api('PATCH','/api/admin/reservations/turnover-b/status',{status:'checked_out'})).status,200);
assert.equal(db.reservations.find(r=>r.id==='turnover-b').actualCheckedOutAt,now);
// Scheduled handoff is bookable before custody returns, with exclusive time windows.
const futureEq = db.equipment.find(e => e.id !== eq.id && e.active && e.reservable && e.status === '가능');
assert.ok(futureEq);
const futureFields = {...fields, reservedDate:'2026-11-10', period:'당일', rentalTime:'17:30', returnTime:'17:10', equipmentItemIds:[futureEq.id]};
futureFields.period = '1박2일';
db.reservations.push({id:'future-a',userId:admin.id,type:'equipment',status:'checked_out',fields:{...futureFields,reservedDate:'2026-11-09',rentalTime:'10:15'},history:[]});
const futureBooking = await api('POST','/api/reservations',{type:'equipment',fields:futureFields});
assert.equal(futureBooking.status,200);
assert.equal((await api('POST','/api/reservations',{type:'equipment',fields:futureFields})).status,409);
assert.equal((await api('POST','/api/reservations',{type:'equipment',fields:{...futureFields,rentalTime:'12:00'}})).status,409);
assert.equal((await api('POST','/api/reservations',{type:'equipment',fields:{...fields,equipmentItemIds:[futureEq.id]}})).status,400);
const snapshot = structuredClone(db);
failSave = true;
assert.equal((await api('PATCH','/api/admin/reservations/turnover-a/return-time',{actualReturnedAt:'2026-10-12T08:10:00Z',reason:'정시 반납 확인'})).status,500);
assert.deepEqual(db,snapshot);
failSave = false;
const list = await api('GET','/api/admin/warnings?source=equipment_overdue');
assert.equal(list.status,200);
assert.equal(list.body.data.total,1);
assert.equal(list.body.data.items[0].status,'confirmed');
console.log('Equipment turnover API checks passed.');
